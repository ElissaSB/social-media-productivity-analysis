print("============================================")
print("Q2: Gender differences in productivity")
print("============================================\n")

# ------------------------------------------------------------
# 0. REQUIRED IMPORTS (SAFE TO KEEP)
# ------------------------------------------------------------

import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats

# ------------------------------------------------------------
# 1. PREPARE GROUPS
# ------------------------------------------------------------

# Keep only Male / Female
mask = data["gender"].isin(["Male", "Female"])
q2_data = data[mask].copy()

group_m = q2_data[q2_data["gender"] == "Male"]["productivity"]
group_f = q2_data[q2_data["gender"] == "Female"]["productivity"]

print(f"Sample size (Male)   : n = {len(group_m)}")
print(f"Sample size (Female) : n = {len(group_f)}\n")

print("Group means and std:")
print(f"  Male   → mean = {group_m.mean():.3f}, std = {group_m.std(ddof=1):.3f}")
print(f"  Female → mean = {group_f.mean():.3f}, std = {group_f.std(ddof=1):.3f}\n")

# ------------------------------------------------------------
# 2. TWO-SAMPLE T-TEST (WELCH)
# ------------------------------------------------------------

t_stat, p_val = stats.ttest_ind(group_m, group_f, equal_var=False)

print("📌 Welch Two-sample t-test (Productivity by Gender)")
print(f"   t-statistic = {t_stat:.3f}")
print(f"   p-value     = {p_val:.4e}\n")

# ------------------------------------------------------------
# 3. EFFECT SIZE (COHEN'S d)
# ------------------------------------------------------------

mean_m = group_m.mean()
mean_f = group_f.mean()

std_pooled = np.sqrt(
    ((len(group_m) - 1) * group_m.var(ddof=1) +
     (len(group_f) - 1) * group_f.var(ddof=1)) /
    (len(group_m) + len(group_f) - 2)
)

cohen_d = (mean_m - mean_f) / std_pooled

print("📌 Effect size (Cohen's d)")
print(f"   d = {cohen_d:.3f}")

if abs(cohen_d) < 0.2:
    print("   → Very small / negligible difference.")
elif abs(cohen_d) < 0.5:
    print("   → Small effect.")
elif abs(cohen_d) < 0.8:
    print("   → Medium effect.")
else:
    print("   → Large effect.")
print()

# ------------------------------------------------------------
# 4. VISUALIZATIONS (CLEAN & BLUE ONLY)
# ------------------------------------------------------------

fig, ax = plt.subplots(1, 2, figsize=(14, 5))

# ---- Boxplot ----
sns.boxplot(
    x="gender",
    y="productivity",
    data=q2_data,
    ax=ax[0],
    color="#1f77b4"
)

ax[0].set_title("Productivity by Gender (Boxplot)", fontsize=12)
ax[0].set_xlabel("Gender", fontsize=11)
ax[0].set_ylabel("Productivity score (0–10)", fontsize=11)

# ---- Violin plot with box inside ----
sns.violinplot(
    x="gender",
    y="productivity",
    data=q2_data,
    ax=ax[1],
    inner="box",
    cut=0,
    color="#1f77b4"
)

ax[1].set_title("Productivity Distribution by Gender", fontsize=12)
ax[1].set_xlabel("Gender", fontsize=11)
ax[1].set_ylabel("Productivity score (0–10)", fontsize=11)

plt.tight_layout()
plt.show()

# ------------------------------------------------------------
# 5. INTERPRETATION SUMMARY
# ------------------------------------------------------------

print("======================================================")
print("Q2 — INTERPRETATION SUMMARY")
print("======================================================")

alpha = 0.05

if p_val < alpha:
    higher_group = "Male" if mean_m > mean_f else "Female"
    diff = abs(mean_m - mean_f)
    print(f"✔ The difference in mean productivity between genders is statistically significant (p < {alpha}).")
    print(f"  • {higher_group} group has the higher average productivity.")
    print(f"  • Mean difference ≈ {diff:.3f} points.")
else:
    print(f"✔ The t-test does NOT find a statistically significant difference in mean productivity between genders "
          f"(p = {p_val:.4f} ≥ {alpha}).")
    print("  → Any observed difference in sample means could be due to random variation.")

print(f"\nEffect size (Cohen's d) = {cohen_d:.3f}.")
print("======================================================")
print("End of Q2")
print("======================================================")

