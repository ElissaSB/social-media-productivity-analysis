from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.cluster import KMeans

# ------------------------------------------------------------
# 1. SELECT FEATURES FOR CLUSTERING
# ------------------------------------------------------------

cluster_vars = [
    "social_media_time",
    "productivity",
    "stress",
    "sleep_hours",
    "burnout_days",
    "coffee_intake"
]

X = data[cluster_vars].copy()

print("Variables selected for clustering:")
for v in cluster_vars:
    print(" •", v)
print("\n")

# ------------------------------------------------------------
# 2. STANDARDIZE DATA
# ------------------------------------------------------------

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

print("✔ Data standardized using StandardScaler.\n")

# ------------------------------------------------------------
# 3. PCA (REDUCE TO 2 COMPONENTS FOR VISUALIZATION)
# ------------------------------------------------------------

pca = PCA(n_components=2)
X_pca = pca.fit_transform(X_scaled)

print("PCA Explained Variance:")
print(f" • PC1: {pca.explained_variance_ratio_[0]:.3f}")
print(f" • PC2: {pca.explained_variance_ratio_[1]:.3f}\n")

# ------------------------------------------------------------
# 4. K-MEANS CLUSTERING (K=3)
# ------------------------------------------------------------

kmeans = KMeans(n_clusters=3, n_init=10, random_state=42)
clusters = kmeans.fit_predict(X_pca)

data["cluster"] = clusters

print("✔ K-Means applied with k = 3 clusters.\n")

# ------------------------------------------------------------
# 5. VISUALIZATION OF CLUSTERS
# ------------------------------------------------------------

plt.figure(figsize=(10, 6))

sns.scatterplot(
    x=X_pca[:, 0],
    y=X_pca[:, 1],
    hue=[f"Cluster {c}" for c in clusters],
    palette="viridis",
    s=35,
    alpha=0.6
)

plt.title("PCA Clusters (K=3)")
plt.xlabel("PC1")
plt.ylabel("PC2")
plt.legend(title="Cluster")
plt.tight_layout()
plt.show()

# ------------------------------------------------------------
# 6. CLUSTER CENTROIDS (IN ORIGINAL VARIABLE SPACE)
# ------------------------------------------------------------

centroids_scaled = kmeans.cluster_centers_
centroids_original = scaler.inverse_transform(
    pca.inverse_transform(centroids_scaled)
)

centroid_df = pd.DataFrame(
    centroids_original, columns=cluster_vars
)

print("======================================================")
print("CLUSTER CENTROIDS (Approximate Profile for Each Group)")
print("======================================================")
print(centroid_df)
print("\n")

# ------------------------------------------------------------
# 7. INTERPRETATION SUMMARY
# ------------------------------------------------------------

print("======================================================")
print("Q5 — INTERPRETATION SUMMARY")
print("======================================================")

for i in range(3):
    print(f"\nCluster {i}:")
    row = centroid_df.loc[i]

    # Behavioral interpretation
