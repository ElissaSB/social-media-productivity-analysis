# Q1 — EFFECT OF SOCIAL MEDIA TIME ON PRODUCTIVITY
# ============================================================

import numpy as np
import pandas as pd

import matplotlib.pyplot as plt
import seaborn as sns

from scipy import stats
import statsmodels.api as sm

print("============================================")
print("Q1: Social Media Time → Productivity")
print("============================================\n")

# ------------------------------------------------------------
# 1. CORRELATION ANALYSIS
# ------------------------------------------------------------

prod_corr, prod_p = stats.pearsonr(
    data["social_media_time"],
    data["productivity"]
)

print("📌 Correlation Result:")
print(f"   • Social Media Time ↔ Productivity : r = {prod_corr:.4f}, p = {prod_p:.4e}\n")

# ------------------------------------------------------------
# 2. SCATTERPLOT WITH REGRESSION LINE
# ------------------------------------------------------------

plt.figure(figsize=(7, 5))

sns.regplot(
    x="social_media_time",
    y="productivity",
    data=data,
    scatter_kws={"alpha": 0.25, "s": 20},
    line_kws={"color": "red", "linewidth": 2}
)

plt.title("Daily Social Media Usage vs Productivity", fontsize=12)
plt.xlabel("Daily social media usage (hours/day)", fontsize=11)
plt.ylabel("Productivity score (0–10)", fontsize=11)

plt.tight_layout()
plt.show()

# ------------------------------------------------------------
# 3. SIMPLE LINEAR REGRESSION (PRODUCTIVITY)
# ------------------------------------------------------------

X = sm.add_constant(data["social_media_time"])
y = data["productivity"]

model = sm.OLS(y, X).fit()

print("\n==============================")
print("Regression: Productivity Model")
print("==============================")
print(model.summary())

# ------------------------------------------------------------
# 4. RESIDUAL DIAGNOSTICS
# ------------------------------------------------------------

plt.figure(figsize=(6, 4))

sns.residplot(
    x=model.fittedvalues,
    y=model.resid,
    lowess=True
)

plt.title("Residuals vs Fitted Values (Productivity Model)")
plt.xlabel("Fitted values")
plt.ylabel("Residuals")

plt.tight_layout()
plt.show()

# ------------------------------------------------------------
# 5. FINAL INTERPRETATION SUMMARY
# ------------------------------------------------------------

print("\n======================================================")
print("Q1 — INTERPRETATION SUMMARY")
print("======================================================")

if prod_p < 0.05:
    effect = "decreases" if prod_corr < 0 else "increases"
    print(f"✔ Social media time significantly {effect} productivity "
          f"(r = {prod_corr:.3f}, p < 0.05).")
else:
    print(f"✔ No statistically significant relationship between social media time "
          f"and productivity (r = {prod_corr:.3f}, p = {prod_p:.4f}).")

print("======================================================")
print("End of Q1")
print("======================================================")

