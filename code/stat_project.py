import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

import statsmodels.api as sm
from statsmodels.stats.outliers_influence import variance_inflation_factor

print("============================================")
print("Q4: Lifestyle factors predicting productivity")
print("============================================\n")

# ------------------------------------------------------------
# 1. SELECT VARIABLES
# ------------------------------------------------------------

predictors = [
    "social_media_time",
    "sleep_hours",
    "coffee_intake",
    "burnout_days",
    "stress"
]

X = data[predictors].copy()
y = data["productivity"]

# Add intercept
X_const = sm.add_constant(X)

# ------------------------------------------------------------
# 2. FIT MULTIPLE REGRESSION MODEL
# ------------------------------------------------------------

model_multi = sm.OLS(y, X_const).fit()

print("\n==============================")
print("MULTIPLE REGRESSION SUMMARY")
print("==============================")
print(model_multi.summary())

# ------------------------------------------------------------
# 3. REGRESSION RESULTS TABLE (FOR REPORT)
# ------------------------------------------------------------

regression_table = pd.DataFrame({
    "Predictor": model_multi.params.index,
    "Coefficient": model_multi.params.values,
    "Std. Error": model_multi.bse.values,
    "p-value": model_multi.pvalues.values
})

# Remove intercept from table (optional, cleaner for report)
regression_table = regression_table[regression_table["Predictor"] != "const"]

print("\n==============================")
print("REGRESSION RESULTS TABLE")
print("==============================")
print(regression_table.round(4))

# ------------------------------------------------------------
# 4. MULTICOLLINEARITY CHECK (VIF)
# ------------------------------------------------------------

vif_df = pd.DataFrame()
vif_df["Predictor"] = X.columns
vif_df["VIF"] = [
    variance_inflation_factor(X.values, i)
    for i in range(X.shape[1])
]

print("\n==============================")
print("VARIANCE INFLATION FACTORS (VIF)")
print("==============================")
print(vif_df.round(3))

# ------------------------------------------------------------
# 5. RESIDUAL DIAGNOSTICS
# ------------------------------------------------------------

fig, ax = plt.subplots(1, 2, figsize=(14, 5))

# Residuals vs Fitted
sns.residplot(
    x=model_multi.fittedvalues,
    y=model_multi.resid,
    lowess=True,
    scatter_kws={"alpha": 0.4},
    ax=ax[0]
)
ax[0].set_title("Residuals vs Fitted")
ax[0].set_xlabel("Fitted Productivity")
